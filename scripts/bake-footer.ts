// Rebuild the original footer collision shapes offline, with the built font.
import { chromium } from "playwright";
import { readFile, writeFile } from "node:fs/promises";
import { startPreview } from "./preview.ts";
const source =
  "data:text/javascript;base64," +
  Buffer.from(await readFile("scripts/lib/glyph-raster.js", "utf8")).toString(
    "base64",
  );
const preview = await startPreview(),
  browser = await chromium.launch();
try {
  const page = await browser.newPage({
    viewport: { width: 1440, height: 900 },
  });
  await page.goto(preview.url + "/?verify");
  await page.waitForFunction(
    () => (window as any).__portfolioPhysics?.letters().length === 18,
  );
  await page.waitForTimeout(3000);
  const data = await page.evaluate(async (source) => {
    const { glyphPolygons, centroid } = await import(source),
      w = window as any,
      M = w.Matter,
      out: any = {};
    for (const l of w.__portfolioPhysics
      .letters()
      .filter((l: any) => !l.hull && !l.el.closest(".dot"))) {
      l.el.style.transform = "none";
      const r = l.el.getBoundingClientRect(),
        cs = getComputedStyle(l.el),
        size = parseFloat(cs.fontSize),
        ctx = document.createElement("canvas").getContext("2d")!;
      ctx.font = `${cs.fontStyle} ${cs.fontWeight} ${cs.fontSize} ${cs.fontFamily}`;
      const metrics = ctx.measureText(l.el.textContent!),
        baseline =
          r.top +
          (parseFloat(cs.lineHeight) -
            metrics.fontBoundingBoxAscent -
            metrics.fontBoundingBoxDescent) /
            2 +
          metrics.fontBoundingBoxAscent;
      const parts = glyphPolygons(l.el, r, cs).flatMap((poly: any) => {
        const c = centroid([poly]),
          body = M.Bodies.fromVertices(c.x, c.y, [poly], {}, true, 0.01, 4);
        return body.parts.length > 1 ? body.parts.slice(1) : [body];
      });
      out[l.el.textContent!] = parts.map((part: any) =>
        part.vertices.map((v: any) => [
          Math.round((((v.x - r.left) * 200) / size) * 1e6) / 1e6,
          Math.round((((v.y - baseline) * 200) / size) * 1e6) / 1e6,
        ]),
      );
    }
    return out;
  }, source);
  await writeFile(
    "scripts/fixtures/footer-polygons.json",
    JSON.stringify(data) + "\n",
  );
  await writeFile(
    "app/ui/public/glyph-footer-data.js",
    "// Generated by scripts/bake-footer.ts. Legacy polygons at 200px, relative to baseline.\nexport default " +
      JSON.stringify(data) +
      ";\n",
  );
} finally {
  await browser.close();
  await preview.close();
}
